import assert from "node:assert/strict";
import {createState,validateState,enqueue,selectActiveJob,cycleDecision,transition,chooseFreeProvider,recordUsage,countWords,validateArticle,validateEvidence} from "./publishing-v2/core.mjs";
const now=Date.parse("2026-11-16T12:00:00Z"),state=createState();
const {job:first}=enqueue(state,{type:"series",id:"101"},now);
assert.equal(cycleDecision(state,now).action,"advance");
assert.throws(()=>enqueue(state,{type:"game",id:"202"},now+1),/Only one active/);
let job=transition(first,"research-started",{},now+1);
job=transition(job,"research-saved",{evidence:{sources:[]}},now+2);
job=transition(job,"part-saved",{part:{text:"section 1"}},now+3);
assert.equal(job.stage,1);
job=transition(job,"provider-deferred",{lastError:"429",nextAttemptAt:now+3600000},now+4);state.jobs[first.key]=job;
assert.equal(cycleDecision(state,now+5).action,"wait");
assert.equal(job.attempts,1,"real provider failures increment retry accounting");
assert.ok(job.nextAttemptAt>=now+3600000,"explicit retry-after remains respected");
assert.equal(selectActiveJob(state.jobs).key,first.key);
assert.equal(cycleDecision(state,now+3600005).action,"resume");
job=transition(job,"resumed",{},now+3600006);assert.equal(job.nextAttemptAt,null);
job=transition(job,"part-saved",{part:{text:"section 2"}},now+3600007);assert.equal(job.attempts,0,"successful stages reset consecutive failures");
job=transition(job,"provider-deferred",{lastError:"administrative wait",nextAttemptAt:now+7200000,countAttempt:false},now+3600008);assert.equal(job.attempts,0,"non-provider deferrals do not increment attempts");
const providers=[{id:"paid",enabled:true,free:false,priority:1},{id:"cool",enabled:true,free:true,priority:2,cooldownUntil:now+5000},{id:"free",enabled:true,free:true,priority:3,dailyRequestLimit:2,dailyTokenLimit:500}];
assert.equal(chooseFreeProvider(providers,{},now).id,"free");
assert.equal(chooseFreeProvider(providers,{"free":{cooldownUntil:now+60000}},now),null,"persisted usage cooldown excludes a failing free provider");
assert.deepEqual(Object.keys(createState()).sort(),["jobs","providerCooldowns","providerUsage","updatedAt","version"].sort(),"provider cooldowns survive state checkpoints");
assert.equal(chooseFreeProvider(providers,{"free":{requests:2}},now),null);
const usage={};recordUsage(usage,"free",{requests:1,tokens:250,success:true});assert.deepEqual(usage.free,{requests:1,tokens:250,successes:1,failures:0});
assert.equal(countWords("هذه مراجعة نقدية من VibeCritic"),5);
const sectionText=prefix=>Array.from({length:220},(_,i)=>prefix+i).join(" ");
const body=["## القصة",sectionText("story"),"## الأنظمة",sectionText("systems"),"## التقييم",sectionText("verdict")].join("\n\n");
const article={title:"عنوان",headline:"عنوان نقدي",summary:"ملخص",verdict:"حكم نقدي",type:"series",sourceId:"series:101",body,storyScore:8,visualsScore:8,soundScore:8,pacingScore:8,score:8,pros:["أ","ب","ج"],cons:["د","هـ"],sources:[{name:"Official",url:"https://example.com/a"},{name:"Independent",url:"https://example.org/b"}],poster:"https://example.com/poster.jpg"};
assert.equal(validateArticle(article).valid,true);
const repeatedBody=["## القصة",sectionText("first"),"## الأنظمة",sectionText("second"),"## التقييم",sectionText("second")].join("\n\n");
const repeatedCheck=validateArticle({...article,body:repeatedBody});
assert.equal(repeatedCheck.valid,false,"near-duplicate analysis sections must be rejected");
assert.equal(repeatedCheck.retryFromStage,3,"regenerate the later overlapping section");
const earlyRepeatBody=["## القصة",sectionText("shared"),"## الأنظمة",sectionText("shared"),"## التقييم",sectionText("distinct")].join("\n\n");
const earlyRepeatCheck=validateArticle({...article,body:earlyRepeatBody});
assert.equal(earlyRepeatCheck.valid,false);
assert.equal(earlyRepeatCheck.retryFromStage,2,"regenerate the earliest later section that overlaps");
assert.equal(validateEvidence({sources:article.sources}).valid,true);
assert.equal(validateEvidence({sources:[{name:"A",url:"https://example.com/a"},{name:"B",url:"https://example.com/b"}]}).valid,false,"same host is not independent evidence");
assert.equal(validateEvidence({sources:[{name:"A",url:"http://example.com/a"},{name:"B",url:"https://example.org/b"}]}).valid,false,"HTTP evidence is rejected");
assert.equal(validateArticle({...article,body:"نص قصير"}).valid,false);
assert.equal(validateArticle({...article,sources:[article.sources[0]]}).valid,false);
assert.equal(validateArticle({...article,sources:[{name:"API",url:"https://api.example.com/a"},{name:"WWW",url:"https://www.example.com/b"}]}).valid,false,"subdomains of one publisher are not independent evidence");
assert.equal(validateArticle({...article,sources:[{name:"TMDB",url:"https://www.themoviedb.org/a"},{name:"Wikipedia",url:"https://en.wikipedia.org/b"}]}).valid,true);
const sameSite=validateEvidence({sources:[{name:"one",url:"https://api.example.co.uk/a"},{name:"two",url:"https://www.example.co.uk/b"}]});
assert.equal(sameSite.valid,false,"two subdomains of one registrable domain count as one source");
const independent=validateEvidence({sources:[{name:"TMDB",url:"https://www.themoviedb.org/a"},{name:"Wikipedia",url:"https://en.wikipedia.org/b"}]});
assert.equal(independent.valid,true);
assert.throws(()=>transition(job,"published"),/Illegal transition/);
// A waiting draft owns the queue: no later candidate may be discovered or enqueued.
const waitingState=createState();
const {job:waitingJob}=enqueue(waitingState,{type:"movie",id:"cooldown"},now);
let delayed=transition(waitingJob,"research-started",{},now+1);
delayed=transition(delayed,"research-saved",{evidence:{sources:[]}},now+2);
delayed=transition(delayed,"part-saved",{part:{text:"saved first stage"}},now+3);
delayed=transition(delayed,"provider-deferred",{lastError:"429",nextAttemptAt:now+7200000},now+4);
waitingState.jobs[waitingJob.key]=delayed;
assert.equal(cycleDecision(waitingState,now+5).action,"wait");
assert.equal(selectActiveJob(waitingState.jobs).key,waitingJob.key);
assert.throws(()=>enqueue(waitingState,{type:"game",id:"newer"},now+6),/Only one active/);
validateState(state);
console.log("VibeCritic Publishing Engine v2 core tests passed.");
